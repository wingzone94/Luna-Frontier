<?php

declare(strict_types=1);
/**
 * Template part for displaying related posts in single.php
 */
$post_id = get_the_ID();
$categories = get_the_category($post_id);
$pool_args = array(
    'post_type'              => 'post',
    'post_status'            => 'publish',
    'post__not_in'           => array($post_id),
    'posts_per_page'         => 30,
    'orderby'                => 'date',
    'order'                  => 'DESC',
    'fields'                 => 'ids',
    'no_found_rows'          => true,
    'ignore_sticky_posts'    => true,
    'update_post_meta_cache' => false,
    'update_post_term_cache' => false,
);

if ($categories) {
    $cat_ids = array();
    foreach($categories as $cat) $cat_ids[] = $cat->term_id;
    $pool_args['category__in'] = $cat_ids;
}

$pool_ids = get_posts($pool_args);

// Fallback to recent posts if no related posts found in same category
if (empty($pool_ids)) {
    unset($pool_args['category__in']);
    $pool_ids = get_posts($pool_args);
}

$selected_ids = array();
if (!empty($pool_ids)) {
    shuffle($pool_ids);
    $selected_ids = array_slice($pool_ids, 0, 4);
}

$related_query = $selected_ids
    ? new WP_Query(array(
        'post_type'           => 'post',
        'post_status'         => 'publish',
        'post__in'            => $selected_ids,
        'posts_per_page'      => count($selected_ids),
        'orderby'             => 'post__in',
        'no_found_rows'       => true,
        'ignore_sticky_posts' => true,
    ))
    : new WP_Query(array('post__in' => array(0)));
if ($selected_ids) {
    update_post_thumbnail_cache($related_query);
}

if ($related_query->have_posts()) :
?>
<section class="m3-related-posts m3-related-posts--simple">
    <div class="m3-related-posts__inner">
        <h2 class="m3-related-posts__title">RELATED POSTS</h2>
        <div class="m3-related-grid">
            <?php while ($related_query->have_posts()) : $related_query->the_post(); ?>
                <a href="<?php the_permalink(); ?>" class="m3-related-card">
                    <?php
                    $lf_rel_thumb_html = '';
                    if ( has_post_thumbnail() ) {
                        $lf_rel_thumb_html = get_the_post_thumbnail(
                            get_the_ID(),
                            'medium_large',
                            array(
                                'alt' => '', // The adjacent title names this link.
                            )
                        );
                    }
                    ?>
                    <?php if ( '' !== trim( $lf_rel_thumb_html ) ) : ?>
                        <div class="m3-related-card__image">
                            <?php echo $lf_rel_thumb_html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_the_post_thumbnail(). ?>
                        </div>
                    <?php else : ?>
                        <div class="m3-related-card__image m3-related-card__image--placeholder">
                            <span class="lf-post-placeholder material-symbols-outlined" data-icon="article" aria-hidden="true"></span>
                        </div>
                    <?php endif; ?>
                    <div class="m3-related-card__content">
                        <h3 class="m3-related-card__title"><?php the_title(); ?></h3>
                    </div>
                </a>
            <?php endwhile; wp_reset_postdata(); ?>
        </div>
    </div>
</section>
<?php endif; ?>
